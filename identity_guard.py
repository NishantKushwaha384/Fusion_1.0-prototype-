# ── NORMALIZATION ─────────────────────────────────────────────

_CONTRACTIONS = {
    r"who's": "who is", r"what's": "what is", r"whats": "what is",
    r"who're": "who are", r"you're": "you are", r"ur": "you are",
    r"i'm": "i am", r"aren't": "are not", r"isn't": "is not",
    r"don't": "do not", r"doesn't": "does not", r"can't": "can not",
    r"whos": "who is",
}

_SAFE_SLANG = {
    r"\bu\b": "you", r"\br\b": "are", r"\bwat\b": "what",
    r"\bwot\b": "what", r"\bwru\b": "who are you",
    r"\bwuu2\b": "what are you", r"\bwho r u\b": "who are you",
}

def normalize(text: str) -> str:
    if not isinstance(text, str):
        return ""
    text = unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode('ascii')
    text = text.lower().strip()
    for token, replacement in _CONTRACTIONS.items():
        text = re.sub(rf"\b{re.escape(token)}\b", replacement, text)
    for pattern, replacement in _SAFE_SLANG.items():
        text = re.sub(pattern, replacement, text)
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


